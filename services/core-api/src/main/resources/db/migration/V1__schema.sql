-- ContextShield · esquema inicial (PostgreSQL; também roda no H2 em modo PostgreSQL nos testes)

CREATE SEQUENCE tx_seq START WITH 184;
CREATE SEQUENCE incident_seq START WITH 1284;

CREATE TABLE customer (
    id              VARCHAR(20) PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    first_name      VARCHAR(60)  NOT NULL,
    initials        VARCHAR(4)   NOT NULL,
    email           VARCHAR(160) NOT NULL UNIQUE,
    phone_mask      VARCHAR(30),
    city            VARCHAR(80),
    since           DATE         NOT NULL,
    segment         VARCHAR(30),
    avg_ticket_90d  NUMERIC(12,2) NOT NULL,
    purchases_90d   INTEGER      NOT NULL
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    name          VARCHAR(120) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    customer_id   VARCHAR(20)  REFERENCES customer(id),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE card (
    id           VARCHAR(30) PRIMARY KEY,
    customer_id  VARCHAR(20) NOT NULL REFERENCES customer(id),
    last4        VARCHAR(4)  NOT NULL,
    holder       VARCHAR(120),
    product      VARCHAR(60),
    kind         VARCHAR(30),
    expiry       VARCHAR(7),
    credit_limit NUMERIC(12,2),
    available    NUMERIC(12,2),
    status       VARCHAR(20)
);

CREATE TABLE device (
    id          VARCHAR(30) PRIMARY KEY,
    customer_id VARCHAR(20) NOT NULL REFERENCES customer(id),
    name        VARCHAR(80) NOT NULL,
    detail      VARCHAR(120),
    kind        VARCHAR(20),
    location    VARCHAR(120),
    first_seen  TIMESTAMP NOT NULL,
    last_seen   TIMESTAMP,
    trusted     BOOLEAN NOT NULL
);

CREATE TABLE address (
    id       VARCHAR(40) PRIMARY KEY,
    label    VARCHAR(60) NOT NULL,
    line1    VARCHAR(160) NOT NULL,
    line2    VARCHAR(120),
    district VARCHAR(80),
    city     VARCHAR(80),
    zip      VARCHAR(12),
    kind     VARCHAR(20) NOT NULL
);

CREATE TABLE address_owner (
    address_id  VARCHAR(40) NOT NULL REFERENCES address(id),
    customer_id VARCHAR(20) NOT NULL REFERENCES customer(id),
    PRIMARY KEY (address_id, customer_id)
);

CREATE TABLE merchant (
    id          VARCHAR(20) PRIMARY KEY,
    name        VARCHAR(80) NOT NULL,
    legal_name  VARCHAR(160),
    domain      VARCHAR(120),
    cnpj        VARCHAR(20),
    city        VARCHAR(80),
    category    VARCHAR(120),
    since       DATE NOT NULL,
    verified    BOOLEAN NOT NULL,
    marketplace BOOLEAN NOT NULL
);

CREATE TABLE seller (
    id           VARCHAR(20) PRIMARY KEY,
    name         VARCHAR(80) NOT NULL,
    initials     VARCHAR(4),
    color        VARCHAR(10),
    tagline      VARCHAR(160),
    about        TEXT,
    since        DATE NOT NULL,
    city         VARCHAR(80),
    cnpj         VARCHAR(20),
    sales        INTEGER NOT NULL,
    rating       NUMERIC(3,1) NOT NULL,
    review_count INTEGER,
    tier         VARCHAR(20) NOT NULL,
    claims_rate  NUMERIC(5,2) NOT NULL
);

CREATE TABLE category (
    slug  VARCHAR(40) PRIMARY KEY,
    name  VARCHAR(80) NOT NULL,
    blurb VARCHAR(200)
);

CREATE TABLE product (
    id            VARCHAR(20) PRIMARY KEY,
    sku           VARCHAR(40),
    name          VARCHAR(120) NOT NULL,
    line          VARCHAR(120),
    category_slug VARCHAR(40) NOT NULL REFERENCES category(slug),
    seller_id     VARCHAR(20) NOT NULL REFERENCES seller(id),
    price         NUMERIC(12,2) NOT NULL,
    old_price     NUMERIC(12,2),
    installments  INTEGER,
    rating        NUMERIC(3,1),
    review_count  INTEGER,
    stock         INTEGER NOT NULL,
    delivery_days INTEGER,
    image         VARCHAR(120),
    tag           VARCHAR(40),
    description   TEXT
);

CREATE TABLE transactions (
    id              VARCHAR(20) PRIMARY KEY,
    customer_id     VARCHAR(20) NOT NULL REFERENCES customer(id),
    merchant_id     VARCHAR(20) NOT NULL REFERENCES merchant(id),
    device_id       VARCHAR(30) NOT NULL REFERENCES device(id),
    address_id      VARCHAR(40) NOT NULL REFERENCES address(id),
    card_id         VARCHAR(30),
    amount          NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    description     VARCHAR(200),
    declared_origin VARCHAR(20),
    coach_script    TEXT,
    scenario        VARCHAR(30),
    status          VARCHAR(30) NOT NULL,
    unavailable     VARCHAR(120),
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL,
    version         INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX ix_tx_customer ON transactions(customer_id);
CREATE INDEX ix_tx_status ON transactions(status);
CREATE INDEX ix_tx_address ON transactions(address_id);

CREATE TABLE transaction_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id      VARCHAR(20) NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    product_id VARCHAR(20),
    seller_id  VARCHAR(20),
    name       VARCHAR(160) NOT NULL,
    quantity   INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL
);

CREATE TABLE assessment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id             VARCHAR(20) NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    stage             VARCHAR(20) NOT NULL,
    score             INTEGER NOT NULL,
    band              VARCHAR(20) NOT NULL,
    level             VARCHAR(20) NOT NULL,
    confidence        INTEGER NOT NULL,
    proposed_decision VARCHAR(30) NOT NULL,
    decision          VARCHAR(30) NOT NULL,
    rule_id           VARCHAR(10) NOT NULL,
    rule_text         TEXT,
    fragility         VARCHAR(20),
    duration_ms       DOUBLE PRECISION,
    engine            VARCHAR(30),
    payload           TEXT NOT NULL,
    created_at        TIMESTAMP NOT NULL
);
CREATE INDEX ix_assessment_tx ON assessment(tx_id);

CREATE TABLE verification (
    tx_id       VARCHAR(20) PRIMARY KEY REFERENCES transactions(id) ON DELETE CASCADE,
    answers     TEXT NOT NULL,
    answered_at TIMESTAMP NOT NULL
);

CREATE TABLE status_change (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id       VARCHAR(20) NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    from_status VARCHAR(30),
    to_status   VARCHAR(30) NOT NULL,
    reason      TEXT,
    actor       VARCHAR(120),
    at          TIMESTAMP NOT NULL
);

CREATE TABLE incident (
    id               VARCHAR(20) PRIMARY KEY,
    customer_id      VARCHAR(20) NOT NULL REFERENCES customer(id),
    tx_id            VARCHAR(20) REFERENCES transactions(id) ON DELETE SET NULL,
    type             VARCHAR(20) NOT NULL,
    channel          VARCHAR(20) NOT NULL,
    description      TEXT NOT NULL,
    contact_handle   VARCHAR(60),
    contact_link     VARCHAR(200),
    destination_text VARCHAR(200),
    occurred_at      TIMESTAMP,
    status           VARCHAR(20) NOT NULL,
    closed_as        VARCHAR(20),
    close_note       TEXT,
    created_at       TIMESTAMP NOT NULL,
    assigned_at      TIMESTAMP,
    closed_at        TIMESTAMP
);
CREATE INDEX ix_incident_customer ON incident(customer_id);

CREATE TABLE intel_entity (
    id         VARCHAR(60) PRIMARY KEY,
    kind       VARCHAR(20) NOT NULL,
    display_value VARCHAR(200) NOT NULL,
    sub        VARCHAR(200),
    first_seen TIMESTAMP NOT NULL,
    last_seen  TIMESTAMP NOT NULL
);

CREATE TABLE intel_mention (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id   VARCHAR(60) NOT NULL REFERENCES intel_entity(id) ON DELETE CASCADE,
    incident_id VARCHAR(20) REFERENCES incident(id) ON DELETE CASCADE,
    tx_id       VARCHAR(20),
    customer_id VARCHAR(20) NOT NULL,
    reason      VARCHAR(300),
    at          TIMESTAMP NOT NULL
);
CREATE INDEX ix_mention_entity ON intel_mention(entity_id);

CREATE TABLE alert (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(20) NOT NULL REFERENCES customer(id),
    tx_id       VARCHAR(20) REFERENCES transactions(id) ON DELETE SET NULL,
    kind        VARCHAR(20) NOT NULL,
    title       VARCHAR(160) NOT NULL,
    body        TEXT NOT NULL,
    read_at     TIMESTAMP,
    created_at  TIMESTAMP NOT NULL
);
CREATE INDEX ix_alert_customer ON alert(customer_id);

CREATE TABLE audit_entry (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at     TIMESTAMP NOT NULL,
    actor  VARCHAR(160) NOT NULL,
    action VARCHAR(60) NOT NULL,
    target VARCHAR(60),
    detail TEXT
);

-- Configuração do motor que o analista pode ligar e desligar no painel (flags e fontes fora do ar)
CREATE TABLE engine_setting (
    setting_key   VARCHAR(60) PRIMARY KEY,
    setting_value VARCHAR(20) NOT NULL
);
