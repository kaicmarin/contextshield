-- Políticas de risco e o laboratório de machine learning.
-- Não altera tabelas anteriores. A política publicada da fintech começa sem sobreposição:
-- o motor continua com os pesos de regras-v2.0.

CREATE TABLE risk_policy (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    version       INTEGER      NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    profile       VARCHAR(30)  NOT NULL,
    weights_json  TEXT         NOT NULL,
    note          VARCHAR(500),
    created_by    VARCHAR(160) NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    published_by  VARCHAR(160),
    published_at  TIMESTAMP
);
CREATE INDEX ix_policy_profile ON risk_policy(profile, status);

CREATE TABLE risk_policy_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id  BIGINT       NOT NULL REFERENCES risk_policy(id),
    action     VARCHAR(30)  NOT NULL,
    actor      VARCHAR(160) NOT NULL,
    detail     VARCHAR(500),
    at         TIMESTAMP    NOT NULL
);

CREATE TABLE known_outcome (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id         VARCHAR(20),
    label         VARCHAR(20)  NOT NULL,
    source        VARCHAR(30)  NOT NULL,
    features_json TEXT         NOT NULL,
    created_by    VARCHAR(160) NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE ml_experiment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           VARCHAR(20)  NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    seed           BIGINT,
    example_count  INTEGER,
    requested_by   VARCHAR(160) NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    finished_at    TIMESTAMP,
    error          VARCHAR(500),
    report_json    TEXT
);

CREATE TABLE ml_model (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id    BIGINT,
    algorithm        VARCHAR(40)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    path             VARCHAR(400),
    metrics_json     TEXT,
    data_origin      VARCHAR(40),
    example_count    INTEGER,
    fraud_count      INTEGER,
    legit_count      INTEGER,
    library          VARCHAR(40),
    library_version  VARCHAR(20),
    validation       VARCHAR(10),
    created_at       TIMESTAMP    NOT NULL,
    approved_by      VARCHAR(160),
    approved_at      TIMESTAMP
);

CREATE TABLE ml_shadow (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id            VARCHAR(20),
    model_id         BIGINT,
    algorithm        VARCHAR(40),
    prediction       VARCHAR(20),
    probability      DOUBLE PRECISION,
    engine_decision  VARCHAR(30),
    latency_ms       DOUBLE PRECISION,
    at               TIMESTAMP    NOT NULL,
    error            VARCHAR(300)
);
CREATE INDEX ix_shadow_tx ON ml_shadow(tx_id);

CREATE TABLE weight_suggestion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id  BIGINT,
    weights_json   TEXT         NOT NULL,
    metrics_json   TEXT,
    status         VARCHAR(20)  NOT NULL,
    note           VARCHAR(500),
    created_at     TIMESTAMP    NOT NULL
);

