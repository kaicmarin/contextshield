-- Respostas dadas pelo analista a um relato. Não substitui a trilha de estado
-- (assumir e encerrar continuam na auditoria e no próprio relato).
CREATE TABLE incident_reply (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    VARCHAR(20) NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
    body           TEXT NOT NULL,
    author_email   VARCHAR(160) NOT NULL,
    author_name    VARCHAR(120),
    service_status VARCHAR(20) NOT NULL,
    created_at     TIMESTAMP NOT NULL
);
CREATE INDEX idx_incident_reply_incident ON incident_reply (incident_id, id);
