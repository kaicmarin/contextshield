-- Estudos do laboratório (pesos e regras). Não altera políticas publicadas automaticamente.

CREATE TABLE ml_study (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  BIGINT       NOT NULL DEFAULT 1,
    kind             VARCHAR(20)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    cost_profile     VARCHAR(40),
    seed             BIGINT,
    report_json      TEXT,
    note             VARCHAR(500),
    created_by       VARCHAR(160) NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    finished_at      TIMESTAMP,
    error            VARCHAR(500)
);
CREATE INDEX ix_ml_study_org ON ml_study(organization_id, kind, status);

CREATE TABLE ml_rule_suggestion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id        BIGINT       REFERENCES ml_study(id),
    organization_id BIGINT       NOT NULL DEFAULT 1,
    rule_key        VARCHAR(16)  NOT NULL,
    display_key     VARCHAR(16)  NOT NULL,
    name            VARCHAR(160) NOT NULL,
    summary         VARCHAR(500),
    priority        INTEGER      NOT NULL,
    kind            VARCHAR(64)  NOT NULL,
    params_json     TEXT         NOT NULL DEFAULT '{}',
    outcome         VARCHAR(32)  NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'SUGGESTED',
    note            VARCHAR(500),
    evidence_json   TEXT,
    created_at      TIMESTAMP    NOT NULL
);
CREATE INDEX ix_ml_rule_suggestion_org ON ml_rule_suggestion(organization_id, status);

