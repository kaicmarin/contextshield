-- Organizações da demonstração e a API de parceiros.
-- Não apaga tabela nem linha anterior. Os cadastros existentes ficam na NEXA.

CREATE TABLE organization (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(40) NOT NULL UNIQUE,
    name     VARCHAR(80) NOT NULL,
    profile  VARCHAR(30) NOT NULL
);

INSERT INTO organization (code, name, profile) VALUES
    ('nexa-demo', 'NEXA demonstração', 'fintech'),
    ('market-demo', 'Marketplace demonstração', 'marketplace'),
    ('shop-demo', 'E-commerce demonstração', 'ecommerce');

ALTER TABLE app_user ADD COLUMN organization_id BIGINT;
UPDATE app_user SET organization_id = (SELECT id FROM organization WHERE code = 'nexa-demo');
ALTER TABLE app_user ADD CONSTRAINT fk_user_org FOREIGN KEY (organization_id) REFERENCES organization(id);

ALTER TABLE transactions ADD COLUMN organization_id BIGINT;
UPDATE transactions SET organization_id = (SELECT id FROM organization WHERE code = 'nexa-demo');
ALTER TABLE transactions ADD CONSTRAINT fk_tx_org FOREIGN KEY (organization_id) REFERENCES organization(id);

ALTER TABLE risk_policy ADD COLUMN organization_id BIGINT;
UPDATE risk_policy SET organization_id = (SELECT id FROM organization WHERE code = 'nexa-demo') WHERE profile = 'fintech';
UPDATE risk_policy SET organization_id = (SELECT id FROM organization WHERE code = 'market-demo') WHERE profile = 'marketplace';
UPDATE risk_policy SET organization_id = (SELECT id FROM organization WHERE code = 'shop-demo') WHERE profile = 'ecommerce';
ALTER TABLE risk_policy ADD CONSTRAINT fk_policy_org FOREIGN KEY (organization_id) REFERENCES organization(id);

ALTER TABLE ml_model ADD COLUMN decision_authorized BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE partner_call (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   BIGINT       NOT NULL REFERENCES organization(id),
    idempotency_key   VARCHAR(80)  NOT NULL,
    score             INTEGER,
    decision          VARCHAR(40),
    rule_id           VARCHAR(20),
    payload           TEXT,
    ml_prediction     VARCHAR(20),
    ml_probability    DOUBLE PRECISION,
    created_at        TIMESTAMP    NOT NULL,
    CONSTRAINT uq_partner_idem UNIQUE (organization_id, idempotency_key)
);
