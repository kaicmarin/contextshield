create table ml_model (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    file_name varchar(180) not null,
    algorithm varchar(80) not null,
    feature_set varchar(40) not null,
    status varchar(20) not null,
    path varchar(500) not null,
    metrics_json text,
    validation varchar(20),
    decision_authorized boolean not null,
    library_version varchar(40),
    created_at timestamp not null,
    approved_by varchar(180)
);

create table ml_experiment (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    status varchar(20) not null,
    seed bigint not null,
    example_count int not null,
    requested_by varchar(180) not null,
    created_at timestamp not null,
    finished_at timestamp,
    error varchar(500),
    report_json text,
    work_dir varchar(500)
);

create table ml_shadow (
    id bigint generated by default as identity primary key,
    organization_id bigint not null,
    tx_id varchar(80),
    model_id bigint,
    algorithm varchar(80),
    prediction varchar(20),
    probability double precision,
    engine_decision varchar(40),
    latency_ms double precision,
    error varchar(500),
    stage varchar(20) not null,
    at timestamp not null
);

create table ml_suggestion (
    id bigint generated by default as identity primary key,
    experiment_id bigint not null,
    organization_id bigint not null,
    weights_json text,
    note varchar(500),
    status varchar(20) not null,
    created_at timestamp not null
);

create index ix_ml_model_org on ml_model (organization_id, feature_set, status);
create index ix_ml_shadow_org on ml_shadow (organization_id, tx_id);
