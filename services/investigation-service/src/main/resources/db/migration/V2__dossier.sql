alter table review_case add column priority varchar(20) default 'NORMAL' not null;
alter table review_case add column assignee varchar(180);
alter table review_case add column tx_id varchar(80);

create table review_evidence (
    id bigint generated by default as identity primary key,
    case_id varchar(40) not null,
    organization_id bigint not null,
    kind varchar(40) not null,
    body varchar(2000) not null,
    actor varchar(180) not null,
    at timestamp not null
);

create table review_comment (
    id bigint generated by default as identity primary key,
    case_id varchar(40) not null,
    organization_id bigint not null,
    body varchar(2000) not null,
    actor varchar(180) not null,
    at timestamp not null
);

create index ix_evidence_case on review_evidence (case_id, at);
create index ix_comment_case on review_comment (case_id, at);
